// scripts/update-console-skiplists.ts
// Writes the listings already in the sheets and persistent dedupe store into every browser-console
// script, so a run skips what we already have instead of returning it again.
//
//   npm run console:skiplists
//
// Scripts in console/tool2-under200k/ get Tab 2's listings, scripts in
// console/tool1/ get Tool 1's. The list goes between the @skiplist-start / @skiplist-end markers;
// run this before pasting a script so the list is current.
import "dotenv/config";
import * as fs from "fs";
import * as path from "path";
import { google } from "googleapis";
import { resolveAduTab, tabRange } from "../src/utils/google-sheets";
import { prisma } from "../src/db/client";
// eslint-disable-next-line @typescript-eslint/no-var-requires
const { sheetKeys } = require("./console-sheet-keys");

const KEY_FILE = path.join(__dirname, "..", "amazing-properties-447020-b2f3946f4b3e.json");
const START = "// @skiplist-start";
const END = "// @skiplist-end";

async function tabKeys(sheets: any, target: "main" | "strict"): Promise<{ title: string; keys: string[]; rows: number }> {
  const tab = await resolveAduTab(sheets, target);
  const values: string[][] =
    (await sheets.spreadsheets.values.get({ spreadsheetId: tab.spreadsheetId, range: tabRange(tab.title, "A:Z") })).data.values ?? [];
  const keys = new Set<string>();
  let addrCol = 5, zipCol = 6, rows = 0;
  for (const r of values) {
    if ((r[0] || "").trim() === "Date Found") {
      addrCol = r.indexOf("Address");
      zipCol = r.findIndex((c) => /^zip/i.test(c));
      continue;
    }
    if (!/^\d{1,2}\/\d{1,2}\/\d{4}/.test((r[0] || "").trim())) continue;
    rows++;
    const url = r.find((c) => /^https?:\/\//.test(String(c))) ?? "";
    for (const k of sheetKeys(r[addrCol], zipCol >= 0 ? r[zipCol] : undefined, url)) keys.add(k);
  }

  // Also include dedupe keys from PostgreSQL AduDedupeKey table
  try {
    const dbRows = await prisma.aduDedupeKey.findMany({ select: { dedupKey: true } });
    for (const { dedupKey } of dbRows) {
      const isStrict = dedupKey.startsWith("strict|");
      if (target === "strict" && !isStrict) continue;
      if (target === "main" && isStrict) continue;
      const raw = isStrict ? dedupKey.slice(7) : dedupKey;
      const [street, zip] = raw.split("|");
      if (street && zip) {
        keys.add(`d:${street}|${zip}`);
        const m = street.match(/^\s*([a-z]?\d+)[a-z]?(?:\s*(?:-|&|and)\s*\d+[a-z]?)?\s+(.*)$/);
        const word = m && m[2]?.split(/\s+/).find((w: string) => w && !/^(n|s|e|w|ne|nw|se|sw|north|south|east|west)$/.test(w));
        if (word) keys.add(`a:${m[1]} ${word}|${zip}`);
      }
    }
  } catch (err) {
    console.warn("Could not query AduDedupeKey table from database:", err);
  }

  return { title: tab.title, keys: [...keys].sort(), rows };
}

function block(indent: string, source: string, keys: string[]): string {
  const lines = [];
  for (let i = 0; i < keys.length; i += 8) lines.push(`${indent}  ${keys.slice(i, i + 8).map((k) => JSON.stringify(k)).join(", ")},`);
  return [
    `${indent}${START} — generated by \`npm run console:skiplists\`; don't edit by hand`,
    `${indent}// Listings already in "${source}" + dedupe store (${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC) — skipped`,
    `${indent}const SKIP_KEYS = new Set([`,
    ...lines,
    `${indent}]);`,
    `${indent}const sheetKeys = ${sheetKeys.toString().replace(/\n/g, `\n${indent}`)};`,
    `${indent}const alreadyInSheet = (address, zip, url) => sheetKeys(address, zip, url).some((k) => SKIP_KEYS.has(k));`,
    `${indent}// Also load any listings already seen in this browser tab/session`,
    `${indent}try {`,
    `${indent}  const _prevSeen = JSON.parse(sessionStorage.getItem("__antigravity_seen_listings") || "[]");`,
    `${indent}  if (Array.isArray(_prevSeen)) _prevSeen.forEach((k) => SKIP_KEYS.add(k));`,
    `${indent}} catch {}`,
    `${indent}const markSeen = (address, zip, url) => {`,
    `${indent}  try {`,
    `${indent}    const ks = sheetKeys(address, zip, url);`,
    `${indent}    ks.forEach((k) => SKIP_KEYS.add(k));`,
    `${indent}    const _prev = JSON.parse(sessionStorage.getItem("__antigravity_seen_listings") || "[]");`,
    `${indent}    const _merged = [...new Set([..._prev, ...ks])].slice(-5000);`,
    `${indent}    sessionStorage.setItem("__antigravity_seen_listings", JSON.stringify(_merged));`,
    `${indent}  } catch {}`,
    `${indent}};`,
    `${indent}${END}`,
  ].join("\n");
}

(async () => {
  const auth = new google.auth.GoogleAuth({ keyFile: KEY_FILE, scopes: ["https://www.googleapis.com/auth/spreadsheets.readonly"] });
  const sheets = google.sheets({ version: "v4", auth });
  const main = await tabKeys(sheets, "main");
  const strict = await tabKeys(sheets, "strict");
  console.log(`${main.title}: ${main.rows} listings → ${main.keys.length} keys (sheet + DB)`);
  console.log(`${strict.title}: ${strict.rows} listings → ${strict.keys.length} keys (sheet + DB)`);

  const folders: Array<[string, typeof main]> = [["tool1", main], ["tool2-under200k", strict]];
  for (const [folder, tab] of folders) {
    const dir = path.join(__dirname, "console", folder);
    for (const name of fs.readdirSync(dir).filter((f) => f.endsWith(".js")).sort()) {
      const file = path.join(dir, name);
      const src = fs.readFileSync(file, "utf8");
      const a = src.indexOf(START);
      const b = src.indexOf(END);
      if (a < 0 || b < 0) continue;
      const indent = src.slice(src.lastIndexOf("\n", a) + 1, a);
      const out = src.slice(0, a - indent.length) + block(indent, tab.title, tab.keys) + src.slice(b + END.length);
      fs.writeFileSync(file, out);
      console.log(`  ${folder}/${name}: ${tab.keys.length} keys from ${tab.title}`);
    }
  }
  process.exit(0);
})().catch((err) => {
  console.error(err);
  process.exit(1);
});
